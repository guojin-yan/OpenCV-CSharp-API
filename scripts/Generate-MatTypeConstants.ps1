param(
    [string]$OpenCvVersion = "5.0.0",
    [string]$WorkspaceRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path,
    [string]$OpenCvSourceRoot = "",
    [string]$OutputPath = "",
    [switch]$Check
)

$ErrorActionPreference = "Stop"

$repoRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
function Get-DefaultOpenCvSourceRoot {
    param(
        [Parameter(Mandatory = $true)]
        [string]$WorkspaceRoot,
        [Parameter(Mandatory = $true)]
        [string]$OpenCvVersion
    )

    # Prefer the version-neutral workspace source root when it exists.
    $neutralSourceRoot = Join-Path $WorkspaceRoot "opencv-source"
    if (Test-Path $neutralSourceRoot) {
        return $neutralSourceRoot
    }

    $versionMatch = [regex]::Match($OpenCvVersion, "^(\d+)(?:\.|$)")
    if (-not $versionMatch.Success) {
        throw "OpenCvVersion must start with a numeric major version: $OpenCvVersion"
    }

    # Keep the major-version source directory only as a legacy/current local fallback.
    return Join-Path $WorkspaceRoot "opencv$($versionMatch.Groups[1].Value)-source code"
}

if ([string]::IsNullOrWhiteSpace($OpenCvSourceRoot)) {
    $OpenCvSourceRoot = Get-DefaultOpenCvSourceRoot -WorkspaceRoot $WorkspaceRoot -OpenCvVersion $OpenCvVersion
}

# Upstream OpenCV source leaf directory includes the selected version as factual source artifact identity.
$opencvSource = Join-Path $OpenCvSourceRoot "opencv-$OpenCvVersion"
$interfaceHeader = Join-Path $opencvSource "modules\core\include\opencv2\core\hal\interface.h"

if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $repoRoot "src\OpenCvSharp\Core\MatType.Generated.cs"
}

if (-not (Test-Path $interfaceHeader)) {
    throw "OpenCV interface header was not found: $interfaceHeader"
}

$lines = Get-Content -LiteralPath $interfaceHeader

function Get-MacroValue {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Name
    )

    $pattern = "^\s*#define\s+$([regex]::Escape($Name))\s+(.+?)\s*$"
    foreach ($line in $lines) {
        $match = [regex]::Match($line, $pattern)
        if ($match.Success) {
            return $match.Groups[1].Value.Trim()
        }
    }

    throw "Macro was not found: $Name"
}

function Convert-ToInt {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Value
    )

    $text = $Value.Trim()
    if ($text -match "^\(?1\s*<<\s*(\d+)\)?$") {
        return [int](1 -shl [int]$matches[1])
    }

    if ($text -match "^\(?([0-9]+)\)?$") {
        return [int]$matches[1]
    }

    throw "Unsupported macro value: $Value"
}

$channelMax = Convert-ToInt (Get-MacroValue "CV_CN_MAX")
$channelShift = Convert-ToInt (Get-MacroValue "CV_CN_SHIFT")
$depthMax = 1 -shl $channelShift
$depthMask = $depthMax - 1
$channelMask = ($channelMax - 1) -shl $channelShift
$matrixTypeMask = ($depthMax * $channelMax) - 1

$depthMacros = New-Object System.Collections.Generic.List[object]
foreach ($line in $lines) {
    $match = [regex]::Match($line, "^\s*#define\s+(CV_(?:8U|8S|16U|16S|32S|32F|64F|16F|16BF|Bool|64U|64S|32U))\s+([0-9]+)\s*$")
    if ($match.Success) {
        $depthMacros.Add([pscustomobject]@{
            Name = $match.Groups[1].Value
            Value = [int]$match.Groups[2].Value
        })
    }
}

if ($depthMacros.Count -eq 0) {
    throw "No OpenCV depth macros were found in $interfaceHeader"
}

$typeMacros = New-Object System.Collections.Generic.List[object]
foreach ($depth in $depthMacros) {
    for ($channels = 1; $channels -le 4; $channels++) {
        $name = "$($depth.Name)C$channels"
        $value = ($depth.Value -band $depthMask) + (($channels - 1) -shl $channelShift)
        $typeMacros.Add([pscustomobject]@{
            Name = $name
            DepthName = $depth.Name
            Channels = $channels
            Value = $value
        })
    }
}

