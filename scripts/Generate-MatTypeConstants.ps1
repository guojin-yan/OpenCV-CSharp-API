$newContent = ($content -join [Environment]::NewLine) + [Environment]::NewLine

if ($Check) {
    if (-not (Test-Path $OutputPath)) {
        throw "Generated file was not found: $OutputPath"
    }

    $currentContent = [System.IO.File]::ReadAllText($OutputPath, [System.Text.UTF8Encoding]::new($false, $true))
    if ($currentContent -ne $newContent) {
        throw "Generated MatType constants are out of date. Run scripts/Generate-MatTypeConstants.ps1."
    }

    Write-Host "Generated MatType constants are up to date: $OutputPath"
    return
}

$outputDirectory = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Force $outputDirectory | Out-Null
[System.IO.File]::WriteAllText($OutputPath, $newContent, [System.Text.UTF8Encoding]::new($false))
Write-Host "Generated MatType constants: $OutputPath"
