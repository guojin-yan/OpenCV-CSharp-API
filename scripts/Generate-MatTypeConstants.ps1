$content.Add("        /// <summary>")
$content.Add("        /// Maximum OpenCV depth slot count, equivalent to <c>CV_DEPTH_MAX</c>.")
$content.Add("        /// OpenCV 深度槽数量上限，等价于 <c>CV_DEPTH_MAX</c>。")
$content.Add("        /// </summary>")
$content.Add("        public const int DepthMax = $depthMax;")
$content.Add("")
$content.Add("        /// <summary>")
$content.Add("        /// OpenCV matrix depth mask, equivalent to <c>CV_MAT_DEPTH_MASK</c>.")
$content.Add("        /// OpenCV 矩阵深度掩码，等价于 <c>CV_MAT_DEPTH_MASK</c>。")
$content.Add("        /// </summary>")
$content.Add("        public const int DepthMask = $depthMask;")
