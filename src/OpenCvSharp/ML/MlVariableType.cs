namespace OpenCvSharp.ML
{
    /// <summary>
    /// Specifies OpenCV ML variable types.
    /// 指定 OpenCV ML 变量类型。
    /// </summary>
    public enum MlVariableType
    {
        /// <summary>Numerical ordered variable. 数值有序变量。</summary>
        Numerical = 0,

        /// <summary>Ordered variable. 有序变量。</summary>
        Ordered = 0,

        /// <summary>Categorical variable. 分类变量。</summary>
        Categorical = 1
    }
}
